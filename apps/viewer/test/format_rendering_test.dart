import 'dart:async';
import 'dart:io';
import 'dart:ui' as ui;

import 'package:flutter/painting.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shen_view/src/application/format_detector.dart';
import 'package:shen_view/src/application/image_resource_service.dart';
import 'package:shen_view/src/application/native_decoder.dart';
import 'package:shen_view/src/domain/image_entry.dart';

Future<ui.Image> _load(ImageProvider<Object> provider) async {
  final result = Completer<ui.Image>();
  final stream = provider.resolve(ImageConfiguration.empty);
  late ImageStreamListener listener;
  listener = ImageStreamListener(
    (info, _) {
      if (!result.isCompleted) result.complete(info.image.clone());
      stream.removeListener(listener);
    },
    onError: (Object error, StackTrace? stack) {
      if (!result.isCompleted) result.completeError(error, stack);
      stream.removeListener(listener);
    },
  );
  stream.addListener(listener);
  return result.future.timeout(const Duration(seconds: 45));
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  for (final name in [
    'format_static.png',
    'format_static.jpg',
    'format_static.bmp',
    'format_static.webp',
    'format_static.tiff',
    'format_static.psd',
    'format_static.dds',
    'format_static.jxl',
    'format_static.avif',
    'format_srgb_icc.png',
  ]) {
    test('viewer pixels preserve gradient color and aspect: $name', () async {
      final file = File('testdata/formats/$name');
      final detector = FormatDetector();
      final format = await detector.detect(file);
      if (!['png', 'jpg', 'bmp', 'webp'].contains(name.split('.').last)) {
        try {
          await NativeDecoder().executable();
        } catch (_) {
          markTestSkipped('需要 ImageMagick，设置 SHENVIEW_MAGICK 后运行');
          return;
        }
      }
      final resources = ImageResourceService();
      addTearDown(resources.dispose);
      addTearDown(PaintingBinding.instance.imageCache.clear);
      final stat = file.statSync();
      final entry = ImageEntry(
        file: file,
        format: format,
        width: 4096,
        height: 2160,
        byteLength: stat.size,
        modifiedAt: stat.modified,
      );
      final image = await _load(
        resources.provider(entry, targetWidth: 256, targetHeight: 144),
      );
      addTearDown(image.dispose);
      expect((image.width, image.height), (256, 135));
      final rgba = (await image.toByteData(
        format: ui.ImageByteFormat.rawRgba,
      ))!;
      // Fixed source expectations, not a baseline regenerated by the decoder.
      // They detect washed-out/linear-as-sRGB/dark output and upside-down rows.
      const expected = [
        [42, 44, 50],
        [120, 80, 56],
        [198, 116, 62],
      ];
      for (var row = 0; row < 3; row++) {
        final y = (image.height * [0.125, 0.5, 0.875][row]).floor();
        final offset = (y * image.width + image.width ~/ 2) * 4;
        for (var channel = 0; channel < 3; channel++) {
          expect(
            rgba.getUint8(offset + channel),
            closeTo(expected[row][channel], 6),
            reason: '$name patch $row channel $channel',
          );
        }
        expect(rgba.getUint8(offset + 3), 255);
      }
    });
  }

  for (final name in [
    'hdr_pq.png',
    'hdr_hlg.png',
    'hdr_pq.avif',
    'hdr_hlg.avif',
  ]) {
    test(
      'viewer SDR fallback maps every HDR neutral patch once: $name',
      () async {
        try {
          await NativeDecoder().executable();
        } catch (_) {
          markTestSkipped('需要 ImageMagick HDRI');
          return;
        }
        final file = File('testdata/formats/$name');
        final stat = file.statSync();
        final resources = ImageResourceService();
        addTearDown(resources.dispose);
        addTearDown(PaintingBinding.instance.imageCache.clear);
        final entry = ImageEntry(
          file: file,
          format: await FormatDetector().detect(file),
          width: 384,
          height: 192,
          byteLength: stat.size,
          modifiedAt: stat.modified,
        );
        final image = await _load(resources.provider(entry));
        addTearDown(image.dispose);
        expect((image.width, image.height), (384, 192));
        final rgba = (await image.toByteData(
          format: ui.ImageByteFormat.rawRgba,
        ))!;
        // Analytic reference: Reinhard(L/203), followed by sRGB, rounded to 8 bit.
        // This checks the rendered fallback, not only the HDR decoder's floats.
        const expected = [0, 156, 188, 213, 228, 235];
        for (var patch = 0; patch < 6; patch++) {
          final at = (32 * image.width + patch * 64 + 32) * 4;
          for (var c = 0; c < 3; c++) {
            expect(
              rgba.getUint8(at + c),
              closeTo(expected[patch], 3),
              reason: '$name patch $patch',
            );
          }
          expect(rgba.getUint8(at + 3), 255);
        }
      },
    );
  }
}
