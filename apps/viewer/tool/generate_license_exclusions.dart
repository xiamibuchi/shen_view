import 'dart:convert';
import 'dart:io';

/// Shared dependencies and third-party notices in runtime packages stay visible,
/// even when their notice names differ from the pub package name.
Future<String> generateLicenseExclusions(Directory root) async {
  final graph = jsonDecode(
    await File.fromUri(root.uri.resolve('.dart_tool/package_graph.json'))
        .readAsString(),
  ) as Map<String, dynamic>;
  final packages = {
    for (final package in graph['packages'] as List<dynamic>)
      (package as Map<String, dynamic>)['name'] as String: package,
  };
  final runtime = <String>{};
  void visit(String name) {
    if (!runtime.add(name)) return;
    final package = packages[name]!;
    for (final dependency in package['dependencies'] as List<dynamic>) {
      visit(dependency as String);
    }
  }

  for (final name in graph['roots'] as List<dynamic>) {
    visit(name as String);
  }
  final configFile = File.fromUri(
    root.uri.resolve('.dart_tool/package_config.json'),
  );
  final config =
      jsonDecode(await configFile.readAsString()) as Map<String, dynamic>;
  final runtimeNames = <String>{...runtime};
  final developmentNames = <String>{};
  final separator = '\n${'-' * 80}\n';
  for (final entry in config['packages'] as List<dynamic>) {
    final package = entry as Map<String, dynamic>;
    final name = package['name'] as String;
    final names = runtime.contains(name) ? runtimeNames : developmentNames;
    names.add(name);
    final packageRoot = Directory.fromUri(
      configFile.uri.resolve(package['rootUri'] as String),
    ).uri;
    var file = File.fromUri(packageRoot.resolve('NOTICES'));
    if (!await file.exists()) {
      file = File.fromUri(packageRoot.resolve('LICENSE'));
    }
    if (!await file.exists()) continue;
    final sections = (await file.readAsString())
        .replaceAll('\r\n', '\n')
        .split(separator);
    if (sections.length == 1) continue;
    for (final section in sections) {
      final split = section.indexOf('\n\n');
      if (split >= 0) names.addAll(section.substring(0, split).split('\n'));
    }
  }
  final excluded = developmentNames.difference(runtimeNames).toList()..sort();
  final output = StringBuffer()
    ..writeln(
      '// Generated by tool/generate_license_exclusions.dart. Do not edit.',
    )
    ..writeln(
      '// Runtime dependencies take precedence over development dependencies.',
    )
    ..writeln('const developmentOnlyLicenseNames = <String>{');
  for (final name in excluded) {
    final escaped = name.replaceAll(r'\', r'\\').replaceAll("'", r"\'");
    output.writeln("  '$escaped',");
  }
  return (output..writeln('};')).toString();
}

Future<void> main() async {
  final root = Directory.fromUri(Platform.script.resolve('../'));
  final target = File.fromUri(
    root.uri.resolve('lib/src/application/license_exclusions.g.dart'),
  );
  await target.writeAsString(await generateLicenseExclusions(root));
  stdout.writeln('Updated ${target.path}');
}
