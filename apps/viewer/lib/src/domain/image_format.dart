enum ImageFormat {
  jpeg,
  png,
  gif,
  webp,
  bmp,
  ico,
  tiff,
  apng,
  heic,
  heif,
  avif,
  jxl,
  psd,
  raw,
  exr,
  hdr,
  hdrVideo,
  dds,
  svg,
  archive,
  unknown,
}

extension ImageFormatLabel on ImageFormat {
  String get label => switch (this) {
    ImageFormat.jpeg => 'JPEG',
    ImageFormat.png => 'PNG',
    ImageFormat.gif => 'GIF',
    ImageFormat.webp => 'WebP',
    ImageFormat.bmp => 'BMP',
    ImageFormat.ico => 'ICO',
    ImageFormat.tiff => 'TIFF',
    ImageFormat.apng => 'APNG',
    ImageFormat.heic => 'HEIC',
    ImageFormat.heif => 'HEIF',
    ImageFormat.avif => 'AVIF',
    ImageFormat.jxl => 'JPEG XL',
    ImageFormat.psd => 'PSD',
    ImageFormat.raw => 'RAW',
    ImageFormat.exr => 'EXR',
    ImageFormat.hdr => 'HDR',
    ImageFormat.hdrVideo => 'HDR / Dolby Vision (still)',
    ImageFormat.dds => 'DDS',
    ImageFormat.svg => 'SVG',
    ImageFormat.archive => 'Archive',
    ImageFormat.unknown => 'Unknown',
  };
}
